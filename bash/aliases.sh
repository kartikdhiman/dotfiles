# ================================
# Wayland Clipboard Shortcuts
# Backend: wl-copy / wl-paste (from wl-clipboard)
# Install: sudo apt install wl-clipboard
# ================================

alias copy='wl-copy'      # Copy stdin to clipboard
alias paste='wl-paste'    # Paste clipboard contents

# macOS-compatible names
alias pbcopy='wl-copy'
alias pbpaste='wl-paste'

